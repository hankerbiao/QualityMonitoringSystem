"""Internal result types used by RTY synchronization stages."""

from dataclasses import dataclass, field
from typing import Any

from pymongo import UpdateOne


@dataclass(frozen=True)
class SalesSyncResult:
    """Normalized sales-stage outcome before it is serialized for the API."""

    successful_sources: int
    total_sources: int
    inserted: int = 0
    updated: int = 0
    orders: int = 0
    details: dict[str, Any] = field(default_factory=dict)

    @property
    def success(self) -> bool:
        return self.successful_sources == self.total_sources


@dataclass(frozen=True)
class RepairBackfillPlan:
    """Write plan generated by repair enrichment, before MongoDB is mutated."""

    operations: list[UpdateOne]
    updates_planned: dict[str, int]
    conflict_records: int
    customer_conflicts: int
